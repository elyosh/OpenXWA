/* How the keyboard and controller mappers handle an action. */
typedef enum XwaInputActionKind {
	/* A press sends the key once and sets a held bit (fire = 1, target/roll
	 * modifier = 2) until release. */
	XWA_INPUT_ACTION_KIND_HELD,
	/* Cockpit look. A controller sends the key on every read while held. The
	 * keyboard sends it once and also reports a held state. */
	XWA_INPUT_ACTION_KIND_LOOK,
	/* A command. The keyboard also reports a held state. */
	XWA_INPUT_ACTION_KIND_LOOK_CENTER,
	/* No key. The held state forces the roll axis. */
	XWA_INPUT_ACTION_KIND_ROLL,
	/* A command that also resumes a paused game. */
	XWA_INPUT_ACTION_KIND_PAUSE,
	/* The key once per press. */
	XWA_INPUT_ACTION_KIND_COMMAND,
} XwaInputActionKind;

